STEPS = 24


def rgb_to_256(r: float, g: float, b: float) -> int:
    """Nearest xterm-256 color (6x6x6 cube or grayscale ramp)."""
    def lv(v):
        return 0 if v < 48 else 1 if v < 115 else min(5, int((v - 35) // 40))

    cube = (0, 95, 135, 175, 215, 255)
    ri, gi, bi = lv(r), lv(g), lv(b)
    cdist = (cube[ri] - r) ** 2 + (cube[gi] - g) ** 2 + (cube[bi] - b) ** 2
    gray = (r + g + b) / 3.0
    k = min(max(int(round((gray - 8) / 10)), 0), 23)
    gv = 8 + 10 * k
    gdist = (gv - r) ** 2 + (gv - g) ** 2 + (gv - b) ** 2
    return 232 + k if gdist < cdist else 16 + 36 * ri + 6 * gi + bi


def gradient(anchors, steps: int = STEPS):
    """Piecewise-linear gradient through RGB anchors, as xterm-256 indices."""
    out = []
    n = len(anchors) - 1
    for i in range(steps):
        pos = i / max(steps - 1, 1) * n
        k = min(int(pos), n - 1)
        f = pos - k
        a, b = anchors[k], anchors[k + 1]
        out.append(rgb_to_256(*(a[j] + (b[j] - a[j]) * f for j in range(3))))
    return out
